#Arithmetic Operators-Simple calculations
x=10
y=5

print(x + y)
print(x - y)
print(x / y)
print(x * y)
print(x % y) #Modulus -Returns remainder after division

#Comparison operators-compare values which return a boolean
num1= 50
num2= 67

print(num1 < num2)
print(num1 > num2)
print(num1 <= num2)
print(num1 >= num2)
print(num1 == num2) #Equal to
print(num1 != num2) #Not equal to


#Assignment Operators- Are used to Assign/Store values in a variable
number= 10
print(number)

#Operator Precedence - Order in which operations get executed
number += 2 #Addition assignment


#Logical Operators - and, or, not &&, ||, ! as used in other programming languanges
print( 100 == 30 and 60 > 200 )
print( 100 == 30 or 60 < 200 )
print( not(100 == 30 or 60 < 200) )

